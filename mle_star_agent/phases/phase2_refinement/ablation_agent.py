def _variant_matches_target(variant: dict, target_names: set) -> bool:
    """Return True if `variant` is selected by `target_names`.

    Factorial variants match by factor value: any ``(factor_name, value)`` tuple
    in `target_names` whose value equals the variant's factor value. Probes match
    by exact name (bare string in `target_names`).
    """
    if variant.get("is_factorial"):
        factors = variant.get("factors", {})
        return any(
            isinstance(t, tuple)
            and len(t) == 2
            and factors.get(t[0]) == t[1]
            for t in target_names
        )
    return variant["name"] in target_names


def _is_complete_ablation_results(results: list) -> bool:
    # Slot-completeness check: every variant index must have produced a result.
    # The per-variant runner writes status "success"/"failed" (line ~524) and the
    # skip paths write "skipped"; it never writes "done". Counting "success" here
    # is required — without it an all-successful iteration-0 grid is judged
    # incomplete and its aggregate checkpoint is never saved. "skipped" counts too,
    # because mono (stereo-off) and targeted later iterations legitimately skip
    # variants to fill their slot. (The zero-evidence guard for diagnosis lives in
    # the diagnosis checkpoint gate + empty-ranking scorer, not here.)
    expected = set(range(NUM_ABLATION_VARIANTS))
    seen = {
        int(r.get("variant_index"))
        for r in results
        if (
            isinstance(r, dict)
            and r.get("variant_index") is not None
            and r.get("status") in ("success", "skipped", "failed")
        )
    }
    return seen == expected


def _failure_mode_from_state(state: dict) -> tuple[str, str]:
    diagnosis = state.get("diagnosis_brief") or {}
    failure = diagnosis.get("failure_classification") or {}
    if not isinstance(failure, dict):
        return "", ""
    return failure.get("failure_mode", ""), failure.get("confidence", "")


def _targeted_variant_names_for_state(state: dict) -> set | None:
    n = int(state.get("outer_iteration", 0))
    if n <= 0:
        return None

    failure_mode, confidence = _failure_mode_from_state(state)
    if not failure_mode or confidence == "low":
        return None

    targets = TARGETED_ABLATION_VARIANTS.get(failure_mode)
    if not targets:
        return None

    targets = set(targets)
    # Mono input: drop the stereo-fusion-off condition from the targeted set —
    # ablating stereo fusion is not relevant (there is no _R image) for mono.
    input_modality = state.get("input_modality", "stereo")
    if input_modality == "mono":
        targets.discard(("stereo_fusion", 0))

    diagnosis = state.get("diagnosis_brief") or {}
    best_probe = diagnosis.get("best_probe") or {}
    best_probe_name = best_probe.get("name")
    if best_probe_name:
        targets.add(best_probe_name)

    # Resolve the factor-condition/probe-name targets into concrete variant
    # names via _variant_matches_target. Cap the factorial variants to
    # LITE_ABLATION_FACTORIAL_CAP (probes are always kept); ABLATION_VARIANTS
    # ordering is stable, so the cap is deterministic across restarts.
    factorial_names: list[str] = []
    probe_names: list[str] = []
    for v in ABLATION_VARIANTS:
        if _variant_matches_target(v, targets):
            if v.get("is_factorial"):
                factorial_names.append(v["name"])
            else:
                probe_names.append(v["name"])
    capped_factorial = factorial_names[:config.LITE_ABLATION_FACTORIAL_CAP]
    return set(capped_factorial) | set(probe_names)


def _ablation_lineage(state: dict) -> dict:
    lineage = script_lineage(
        state.get("best_pipeline_script", ""),
        script_key="best_pipeline_script_sha256",
    )
    lineage["ablation_variant_count"] = NUM_ABLATION_VARIANTS
    lineage["ablation_variant_names_sha256"] = stable_json_sha256([
        v["name"] for v in ABLATION_VARIANTS
    ])
    lineage["targeted_ablation_map_sha256"] = stable_json_sha256(TARGETED_ABLATION_VARIANTS)
    return lineage


def _is_ablation_checkpoint_current(data: dict, state: dict) -> bool:
    return lineage_matches(data.get("lineage"), _ablation_lineage(state))

# ---------------------------------------------------------------------------
# Stop-flag checker (sub-agent 1 of ablation_agent)
# Handles two concerns in one FunctionTool:
#   (a) stop_outer_loop  → escalate to exit the outer LoopAgent
#   (b) ablation checkpoint exists → pre-populate result keys so variant steps self-skip
# ---------------------------------------------------------------------------


def check_stop_flag_fn(tool_context) -> str:
    """
    1. If stop_outer_loop is True, set escalate = True to exit the outer LoopAgent.
    2. Otherwise, if ablation_{{N}}.json exists for the current outer_iteration, load
       it and pre-populate ablation_result_N keys so variant steps self-skip.
    3. Otherwise signal CONTINUE.
    """
    if tool_context.state.get("stop_outer_loop", False):
        tool_context.actions.escalate = True
        return "STOP_FLAG_SET: stop_outer_loop is True — escalating to exit the outer loop."

    n = int(tool_context.state.get("outer_iteration", 0))
    ckpt_path = config.ckpt_ablation(n)
    if checkpoint_exists(ckpt_path):
        data = load_checkpoint(ckpt_path)
        results = data.get("ablation_results", [])
        if not _is_ablation_checkpoint_current(data, tool_context.state):
            logger.warning("ablation_%d.json lineage mismatch — ignoring stale checkpoint.", n)
        elif not _is_complete_ablation_results(results):
            logger.warning(
                "ablation_%d.json has %d/%d variant results — ignoring incomplete checkpoint.",
                n,
                len(results),
                NUM_ABLATION_VARIANTS,
            )
        else:
            tool_context.state["ablation_results"] = results
            for r in results:
                idx = r.get("variant_index", 0)
                tool_context.state[f"ablation_result_{idx}"] = r
            return (
                f"CHECKPOINT_FOUND: loaded {len(results)} ablation result(s) for "
                f"outer_iteration={n}. ablation_result_N keys pre-populated — "
                "variant steps will self-skip."
            )

    # Aggregate checkpoint missing, stale, or incomplete — recover whatever
    # per-variant checkpoints already exist so variant agents self-skip without
    # re-generating scripts via LLM.
    current_lineage = _ablation_lineage(tool_context.state)
    recovered = []
    for i in range(NUM_ABLATION_VARIANTS):
        if tool_context.state.get(f"ablation_result_{i}") is not None:
            continue
        variant_ckpt = config.ckpt_ablation_variant(n, i)
        if checkpoint_exists(variant_ckpt):
            vdata = load_checkpoint(variant_ckpt)
            if lineage_matches(vdata.get("lineage"), current_lineage):
                tool_context.state[f"ablation_result_{i}"] = vdata
                recovered.append(i)
                logger.info("Pre-loaded per-variant checkpoint for variant %d into state.", i)
            else:
                logger.warning("Per-variant checkpoint for variant %d has lineage mismatch — will re-run.", i)

    if recovered:
        return (
            f"CHECKPOINT_FOUND: recovered {len(recovered)}/{NUM_ABLATION_VARIANTS} per-variant "
            f"checkpoints for outer_iteration={n} (indices {recovered}). "
            "ablation_result_N keys pre-populated — those variant steps will self-skip."
        )

    return f"CONTINUE: no stop flag, no checkpoint for outer_iteration={n} — proceeding."


check_stop_flag_tool = FunctionTool(func=check_stop_flag_fn)


def _bypass_ablation_flag(callback_context, llm_request):
    try:
        result = check_stop_flag_fn(callback_context)
        return _make_bypass_response(result)
    except Exception as exc:
        logger.warning("bypass_ablation_flag: exception — falling back to LLM: %s", exc)
        return None


