def build_ablation_variants(outer_iteration: int = 0) -> list[dict]:
    """Construct the ablation variant list for an outer iteration.

    On the first outer iteration (or whenever factorial ablation is disabled),
    run the full factorial grid plus the diagnostic probes. On later iterations,
    the factorial grid is narrowed to a targeted/capped subset — but that
    narrowing is enforced at *runtime* via skip records (see
    ``_targeted_variant_names_for_state`` and the per-variant run function), so
    the static agent graph and checkpoint completeness stay anchored to the full
    superset returned here. ``LITE_ABLATION_FACTORIAL_CAP`` therefore bounds how
    many factorial variants actually execute on later iterations, not the list
    length.
    """
    factorial = generate_factorial_variants(ABLATION_FACTORS)
    if outer_iteration == 0 or not config.ABLATION_FACTORIAL_ENABLED:
        return factorial + ABLATION_PROBES
    return factorial[:config.LITE_ABLATION_FACTORIAL_CAP] + ABLATION_PROBES


